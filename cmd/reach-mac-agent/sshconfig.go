// The Mac agent never writes server-supplied text into ~/.ssh. It accepts a
// structured host list, validates every field against a strict grammar, and
// renders the include file from its own template. The result is checked with
// `ssh -G` before it replaces the previous file; on any failure the previous
// file stays in place.
//
// Threat addressed: a compromised hub returning Match exec / ProxyCommand /
// LocalCommand / Include (daybreak P1-3, Opus P1-3), or an agent-reported
// algorithm value that makes OpenSSH reject the whole config (Opus P1-1).

type sshHost struct {
	Host          string      `json:"host"`
	HostName      string      `json:"hostname"`
	Port          int         `json:"port"`
	User          string      `json:"user"`
	ProxyJump     string      `json:"proxy_jump"`
	HostKeyAlias  string      `json:"host_key_alias"`
	MachineID     string      `json:"machine_id"`
	ObservedState string      `json:"observed_state"`
	Options       [][2]string `json:"options,omitempty"`
}

type sshConfigDocument struct {
	Schema        int       `json:"schema"`
	Hosts         []sshHost `json:"hosts"`
	ReservedHosts []string  `json:"reserved_hosts,omitempty"`
}

var (
	hostAliasRE    = regexp.MustCompile(`^[a-z0-9][a-z0-9-]{1,30}[a-z0-9]$`)
	sshTokenRE     = regexp.MustCompile(`^[A-Za-z0-9_.@%+=:,/\\-]+$`)
	hostKeyAliasRE = regexp.MustCompile(`^reach-m_[a-z0-9_]{1,40}$`)
	algoListRE     = regexp.MustCompile(`^[+\-^]?[a-z0-9@.\-]+(,[a-z0-9@.\-]+)*$`)
	stateRE        = regexp.MustCompile(`^[a-z_]{1,16}$`)
)

var allowedOptionNames = map[string]bool{
	"KexAlgorithms":            true,
	"HostKeyAlgorithms":        true,
	"PubkeyAcceptedAlgorithms": true,
	"PubkeyAcceptedKeyTypes":   true,
	"Ciphers":                  true,
	"MACs":                     true,
}

// reservedHost uses the exact list reachd enforces (internal/reserved), so
// even a compromised hub cannot claim those aliases in the include file.
// Extra local reservations come from mac-agent.yaml (reserved_hosts).
func reservedHost(name string, extra []string) bool {
	return reserved.Match(name, extra)
}

func validToken(s string) bool {
	return s != "" && len(s) <= 128 && sshTokenRE.MatchString(s) && !strings.HasPrefix(s, "-")
}

func validateHost(h sshHost, extraReserved ...string) error {
	if !hostAliasRE.MatchString(h.Host) {
		return fmt.Errorf("invalid host alias %q", h.Host)
	}
	if reservedHost(h.Host, extraReserved) {
		return fmt.Errorf("host alias %q is reserved", h.Host)
	}
	if h.HostName != "localhost" && h.HostName != "127.0.0.1" {
		return fmt.Errorf("host %s: hostname must be localhost", h.Host)
	}
	if h.Port < 1 || h.Port > 65535 {
		return fmt.Errorf("host %s: invalid port", h.Host)
	}
	if !validToken(h.User) {
		return fmt.Errorf("host %s: invalid user", h.Host)
	}
	if !validToken(h.ProxyJump) || strings.ContainsAny(h.ProxyJump, "%") {
		return fmt.Errorf("host %s: invalid proxy jump", h.Host)
	}
	if strings.EqualFold(h.ProxyJump, h.Host) {
		return fmt.Errorf("host %s: proxy jump must not be the host itself", h.Host)
	}
	if !hostKeyAliasRE.MatchString(h.HostKeyAlias) {
		return fmt.Errorf("host %s: invalid host key alias", h.Host)
	}
	if h.ObservedState != "" && !stateRE.MatchString(h.ObservedState) {
		return fmt.Errorf("host %s: invalid observed state", h.Host)
	}
	seen := map[string]bool{}
	for _, opt := range h.Options {
		if !allowedOptionNames[opt[0]] || seen[opt[0]] {
			return fmt.Errorf("host %s: option %q not allowed", h.Host, opt[0])
		}
		if len(opt[1]) > 512 || !algoListRE.MatchString(opt[1]) {
			return fmt.Errorf("host %s: invalid %s value", h.Host, opt[0])
		}
		seen[opt[0]] = true
	}
	return nil
}

// sanitizeHosts drops invalid or duplicate hosts so one bad row cannot remove
// every alias; dropped hosts are reported to the caller for logging.
func sanitizeHosts(in []sshHost, extraReserved ...string) ([]sshHost, []error) {
	var out []sshHost
	var errs []error
	seen := map[string]bool{}
	for _, h := range in {
		if err := validateHost(h, extraReserved...); err != nil {
			errs = append(errs, err)
			continue
		}
		if seen[h.Host] {
			errs = append(errs, fmt.Errorf("duplicate host alias %q", h.Host))
			continue
		}
		seen[h.Host] = true
		out = append(out, h)
	}
	return out, errs
}

func renderSSHConfig(hosts []sshHost) string {
	var b strings.Builder
	b.WriteString("# Generated by reach-mac-agent from structured Reach data. Do not edit by hand.\n\n")
	for _, h := range hosts {
		state := h.ObservedState
		if state == "" {
			state = "unknown"
		}
		fmt.Fprintf(&b, "# %s observed=%s\nHost %s\n    HostName %s\n    Port %d\n    User %s\n    ProxyJump %s\n    HostKeyAlias %s\n    StrictHostKeyChecking accept-new\n    ForwardAgent no\n    ForwardX11 no\n    ClearAllForwardings yes\n", strings.TrimPrefix(h.HostKeyAlias, "reach-"), state, h.Host, h.HostName, h.Port, h.User, h.ProxyJump, h.HostKeyAlias)
		for _, opt := range h.Options {
			fmt.Fprintf(&b, "    %s %s\n", opt[0], opt[1])
		}
		b.WriteString("\n")
	}
	return b.String()
}

func parseSSHConfigJSON(body []byte) ([]sshHost, []string, error) {
	var doc sshConfigDocument
	dec := json.NewDecoder(strings.NewReader(string(body)))
	dec.DisallowUnknownFields()
	if err := dec.Decode(&doc); err != nil {
		return nil, nil, fmt.Errorf("parse ssh-config.json: %w", err)
	}
	if doc.Schema != 1 {
		return nil, nil, fmt.Errorf("unsupported ssh-config schema %d", doc.Schema)
	}
	return doc.Hosts, doc.ReservedHosts, nil
}

var errLegacyDirective = errors.New("legacy ssh-config contains a directive outside the allowlist")

// parseLegacySSHConfig reads the text format served by older reachd builds.
// It accepts only the directives Reach itself emits and rejects the whole
// document if anything else appears (Match, Include, *Command, ...).
func parseLegacySSHConfig(body []byte) ([]sshHost, error) {
	var hosts []sshHost
	var cur *sshHost
	sc := bufio.NewScanner(strings.NewReader(string(body)))
	sc.Buffer(make([]byte, 64*1024), 1<<20)
	line := 0
	for sc.Scan() {
		line++
		text := strings.TrimSpace(sc.Text())
		if text == "" || strings.HasPrefix(text, "#") {
			continue
		}
		fields := strings.Fields(text)
		if len(fields) != 2 {
			return nil, fmt.Errorf("%w: line %d", errLegacyDirective, line)
		}
		key, val := fields[0], fields[1]
		if key == "Host" {
			hosts = append(hosts, sshHost{Host: val})
			cur = &hosts[len(hosts)-1]
			continue
		}
		if cur == nil {
			return nil, fmt.Errorf("%w: %s before Host (line %d)", errLegacyDirective, key, line)
		}
		switch key {
		case "HostName":
			cur.HostName = val
		case "Port":
			p, err := strconv.Atoi(val)
			if err != nil {
				return nil, fmt.Errorf("line %d: invalid port", line)
			}
			cur.Port = p
		case "User":
			cur.User = val
		case "ProxyJump":
			cur.ProxyJump = val
		case "HostKeyAlias":
			cur.HostKeyAlias = val
			cur.MachineID = strings.TrimPrefix(val, "reach-")
		case "StrictHostKeyChecking":
			if val != "accept-new" {
				return nil, fmt.Errorf("%w: StrictHostKeyChecking %s (line %d)", errLegacyDirective, val, line)
			}
		case "ForwardAgent", "ForwardX11":
			if val != "no" {
				return nil, fmt.Errorf("%w: %s %s (line %d)", errLegacyDirective, key, val, line)
			}
		case "ClearAllForwardings":
			if val != "yes" {
				return nil, fmt.Errorf("%w: %s %s (line %d)", errLegacyDirective, key, val, line)
			}
		default:
			if !allowedOptionNames[key] {
				return nil, fmt.Errorf("%w: %s (line %d)", errLegacyDirective, key, line)
			}
			cur.Options = append(cur.Options, [2]string{key, val})
		}
	}
	if err := sc.Err(); err != nil {
		return nil, err
	}
	return hosts, nil
}

// validateWithSSH runs `ssh -G -F <candidate> <host>` so OpenSSH itself
// confirms the file parses. The candidate contains only allowlisted
// directives, so -G cannot execute anything. ssh -G parses the whole file
// but only applies the named host's block, so each host with options is
// checked by name.
func validateWithSSH(ctx context.Context, sshBinary, path string, hosts []sshHost) error {
	if len(hosts) == 0 {
		return nil
	}
	names := []string{hosts[0].Host}
	for _, h := range hosts[1:] {
		if len(h.Options) > 0 {
			names = append(names, h.Host)
		}
	}
	for _, name := range names {
		if err := sshG(ctx, sshBinary, path, name); err != nil {
			return err
		}
	}
	return nil
}

func sshG(ctx context.Context, sshBinary, path, host string) error {
	if sshBinary == "" {
		sshBinary = "ssh"
	}
	vctx, cancel := context.WithTimeout(ctx, 10*time.Second)
	defer cancel()
	cmd := exec.CommandContext(vctx, sshBinary, "-G", "-F", path, host)
	cmd.Env = append(os.Environ(), "SSH_AUTH_SOCK=")
	out, err := cmd.CombinedOutput()
	if err != nil {
		msg := strings.TrimSpace(string(out))
		if len(msg) > 400 {
			msg = msg[:400]
		}
		return fmt.Errorf("ssh -G rejected generated config for %s: %v: %s", host, err, msg)
	}
	return nil
}

// installSSHConfig renders hosts, validates the candidate with ssh -G in the
// destination directory, then atomically replaces the previous file.
// If validation fails, each host's options are checked on their own and
// only the hosts whose options OpenSSH rejects lose them (daybreak P1-4,
// round 3 P3-C); everyone else keeps their legacy algorithm overrides.
// droppedOptions lists those hosts (logged by the caller).
var droppedOptions []string

func installSSHConfig(ctx context.Context, sshBinary, outFile string, hosts []sshHost) error {
	droppedOptions = nil
	outFile = expandHome(outFile)
	content := []byte(renderSSHConfig(hosts))
	if prev, err := os.ReadFile(outFile); err == nil && string(prev) == string(content) {
		return nil
	}
	dir := filepath.Dir(outFile)
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return err
	}
	tmp, err := os.CreateTemp(dir, ".reach-validate-*")
	if err != nil {
		return err
	}
	tmpName := tmp.Name()
	defer os.Remove(tmpName)
	if _, err := tmp.Write(content); err != nil {
		_ = tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	if err := validateWithSSH(ctx, sshBinary, tmpName, hosts); err != nil {
		if !hostsHaveOptions(hosts) {
			return err
		}
		fixed := make([]sshHost, len(hosts))
		copy(fixed, hosts)
		for i, h := range fixed {
			if len(h.Options) == 0 {
				continue
			}
			// This host alone, with its options.
			single := []byte(renderSSHConfig([]sshHost{h}))
			if werr := os.WriteFile(tmpName, single, 0o600); werr != nil {
				return werr
			}
			if sshG(ctx, sshBinary, tmpName, h.Host) != nil {
				fixed[i].Options = nil
				droppedOptions = append(droppedOptions, h.Host)
			}
		}
		content = []byte(renderSSHConfig(fixed))
		if werr := os.WriteFile(tmpName, content, 0o600); werr != nil {
			return werr
		}
		if err2 := validateWithSSH(ctx, sshBinary, tmpName, fixed); err2 != nil {
			return fmt.Errorf("%v; and after removing rejected per-host options: %w", err, err2)
		}
	}
	return writeAtomic(outFile, content, 0o600)
}

func hostsHaveOptions(hosts []sshHost) bool {
	for _, h := range hosts {
		if len(h.Options) > 0 {
			return true
		}
	}
	return false
}
